/** WJC 사용자면 일본어, 아니면 원래 문구 */
export function t(text: string): string {
  if (!text || !isJapaneseUser()) return text;
  return ja[text] ?? text;
}

/** 공용 컴포넌트용: enabled(=translate 옵션)일 때만 t() 적용 */
export function useT(enabled: () => boolean | undefined) {
  return (text: string) => (enabled() ? t(text) : text);
}
